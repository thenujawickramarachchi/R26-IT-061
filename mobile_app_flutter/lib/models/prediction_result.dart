class PredictionResult {
  final int year;
  final int week;
  final int calculatedMonth;
  final String predictedOutbreakLevel;
  final double highProbability;
  final double mediumProbability;
  final double lowProbability;
  final String modelUsed;
  final String validation;
  final String inputType;

  final Map<String, dynamic> autoGeneratedFeatures;
  final Map<String, dynamic> dataSourcesUsed;

  const PredictionResult({
    required this.year,
    required this.week,
    required this.calculatedMonth,
    required this.predictedOutbreakLevel,
    required this.highProbability,
    required this.mediumProbability,
    required this.lowProbability,
    required this.modelUsed,
    required this.validation,
    required this.inputType,
    required this.autoGeneratedFeatures,
    required this.dataSourcesUsed,
  });

  factory PredictionResult.fromJson(Map<String, dynamic> json) {
    final probabilities = Map<String, dynamic>.from(
      json['probabilities'] as Map? ?? {},
    );

    return PredictionResult(
      year: (json['year'] as num?)?.toInt() ?? 0,
      week: (json['week'] as num?)?.toInt() ?? 0,
      calculatedMonth: (json['calculated_month'] as num?)?.toInt() ?? 0,

      // Supports both /predict-future and /predict-dashboard response formats
      predictedOutbreakLevel:
          json['predicted_outbreak_level']?.toString() ??
          json['risk_level']?.toString() ??
          'Unknown',

      highProbability: (probabilities['High'] as num?)?.toDouble() ?? 0.0,
      mediumProbability: (probabilities['Medium'] as num?)?.toDouble() ?? 0.0,
      lowProbability: (probabilities['Low'] as num?)?.toDouble() ?? 0.0,

      modelUsed: json['model_used']?.toString() ?? '',
      validation: json['validation']?.toString() ?? '',
      inputType: json['input_type']?.toString() ?? '',

      autoGeneratedFeatures: Map<String, dynamic>.from(
        json['auto_generated_features'] as Map? ?? {},
      ),

      dataSourcesUsed: Map<String, dynamic>.from(
        json['data_sources_used'] as Map? ?? {},
      ),
    );
  }
}
