class PredictionResult {
  final int year;
  final int week;
  final int calculatedMonth;
  final String predictedOutbreakLevel;

  final double highProbability;
  final double mediumProbability;
  final double lowProbability;

  final String modelUsed;
  final String validation;
  final String inputType;

  final Map<String, dynamic> autoGeneratedFeatures;
  final Map<String, dynamic> dataSourcesUsed;

  const PredictionResult({
    required this.year,
    required this.week,
    required this.calculatedMonth,
    required this.predictedOutbreakLevel,
    required this.highProbability,
    required this.mediumProbability,
    required this.lowProbability,
    required this.modelUsed,
    required this.validation,
    required this.inputType,
    required this.autoGeneratedFeatures,
    required this.dataSourcesUsed,
  });

  factory PredictionResult.fromJson(Map<String, dynamic> json) {
    final probabilities = _toMap(json['probabilities']);

    return PredictionResult(
      year: _toInt(json['year']),
      week: _toInt(json['week']),
      calculatedMonth: _toInt(json['calculated_month']),

      predictedOutbreakLevel:
          _toStringValue(json['predicted_outbreak_level']) ??
          _toStringValue(json['risk_level']) ??
          'Unknown',

      highProbability: _toDouble(
        probabilities['High'] ?? probabilities['high'],
      ),

      mediumProbability: _toDouble(
        probabilities['Medium'] ?? probabilities['medium'],
      ),

      lowProbability: _toDouble(probabilities['Low'] ?? probabilities['low']),

      modelUsed: _toStringValue(json['model_used']) ?? 'Unknown',
      validation: _toStringValue(json['validation']) ?? 'Unknown',
      inputType: _toStringValue(json['input_type']) ?? 'Unknown',

      autoGeneratedFeatures: _toMap(json['auto_generated_features']),

      dataSourcesUsed: _toMap(json['data_sources_used']),
    );
  }

  static Map<String, dynamic> _toMap(dynamic value) {
    if (value is Map) {
      return Map<String, dynamic>.from(value);
    }

    return <String, dynamic>{};
  }

  static int _toInt(dynamic value) {
    if (value is int) {
      return value;
    }

    if (value is num) {
      return value.toInt();
    }

    if (value is String) {
      return int.tryParse(value) ?? 0;
    }

    return 0;
  }

  static double _toDouble(dynamic value) {
    if (value is double) {
      return value;
    }

    if (value is num) {
      return value.toDouble();
    }

    if (value is String) {
      return double.tryParse(value) ?? 0.0;
    }

    return 0.0;
  }

  static String? _toStringValue(dynamic value) {
    if (value == null) {
      return null;
    }

    final text = value.toString().trim();

    if (text.isEmpty) {
      return null;
    }

    return text;
  }
}
